const scratch = useScratch();
test('lost server/session stays visible with recovery, one durable event per loss', async () => {
  const config = makeConfig(scratch.sub('loss'));
  const fake = new FakeTmux();
  const { ctx } = makeContext(config, { respond: fake.respond });
  const wt = scratch.sub('worktree');
  const record = seedTask(config, 'LOST', { windowId: '@1', repos: [{ path: wt, worktree: wt }] });
  fs.writeFileSync(sessionsFile(config, record.window), JSON.stringify({ claude: [{ id: 'saved-session' }] }));
  const noSession = seedTask(config, 'FRESH', { windowId: '@2', repos: [{ path: wt, worktree: wt }] });
  seedTask(config, 'LEGACY');
  seedTask(config, 'CLOSED', { closed: true });
  seedTask(config, 'CANCELLED', { cancelled: true });
  fake.add('lost', 'Working');
  fake.add('fresh', 'Working');
  await collectStatus(ctx, { progress: false });
  fake.windows = [];
  const rows = await collectStatus(ctx, { progress: false });
  const lost = rows.find(r => r.task === 'LOST')!;
  assert.equal(lost.state, 'needs-attention');
  assert.equal(lost.finished, false);
  assert.equal(rows.find(r => r.task === 'LEGACY')!.state, 'needs-attention');
  assert.match(lost.hint!, /tmux.*(server|session).*lost|utracono.*tmux/i);
  assert.match(lost.hint!, /agentctl resume LOST/);
  assert.match(rows.find(r => r.task === noSession.task)!.hint!, /re-queue.*new task.*worktree/i);
  assert.deepEqual((await findResumable(ctx)).find(r => r.task === 'LOST')?.sessionId, 'saved-session');
  await collectStatus(ctx, { progress: false });
  const next = makeContext(config, { respond: fake.respond });
  await collectStatus(next.ctx, { progress: false });
  assert.equal(readJournal(config).filter(e => e.kind === 'tmux-lost' && e.task === 'LOST').length, 1);
  assert.equal(readJournal(config).filter(e => e.kind === 'tmux-lost' && ['CLOSED', 'CANCELLED'].includes(e.task!)).length, 0);
  fake.add('watch');
  assert.equal((await collectStatus(ctx, { progress: false })).find(r => r.task === 'LOST')!.state, 'needs-attention');
  fake.add('lost', 'Working');
  await collectStatus(ctx, { progress: false });
  fake.windows = [];
  await collectStatus(ctx, { progress: false });
  assert.equal(readJournal(config).filter(e => e.kind === 'tmux-lost' && e.task === 'LOST').length, 2);
});
test('SessionStart remembers session before the first prompt and is available to resume', async () => {
  const config = makeConfig(scratch.sub('early'));
  const { ctx } = makeContext(config);
  const wt = scratch.sub('early-wt');
  const record = seedTask(config, 'EARLY', { attemptId: 'attempt-early', repos: [{ path: wt, worktree: wt }] });
  const settings = buildClaudeSettings('EARLY', ['node', '/agentctl.js'], undefined, record.attemptId) as { hooks: Record<string, unknown> };
  assert.ok(settings.hooks.SessionStart);
  const alerts = new Alerts(ctx, { notify: async () => {} });
  await handleEvent(ctx, alerts, { task: 'EARLY', agent: 'claude', kind: 'session-start' as never, attempt: record.attemptId, payload: { session_id: 'early-id', transcript_path: path.join(wt, 'early.jsonl') } });
  assert.equal(readTaskSessions(config, record.window).claude?.[0]?.id, 'early-id');
  assert.equal(fs.existsSync(path.join(config.stateDir, record.window, 'transcript-session.json')), false, 'early session receipt must not pin a not-yet-created transcript');
  assert.equal((await findResumable(ctx))[0]?.sessionId, 'early-id');
});
