import assert from 'node:assert/strict';
import { it } from 'node:test';
import { z } from 'zod';
import { Context } from '../src/core/context.ts';
import { MCP_TOOLS, applyMcpRequest } from '../src/core/mcp-tools.ts';
import { recordMcpRequest, applyMcpRequests } from '../src/core/mcp-requests.ts';
import { saveEntry, readQueue } from '../src/core/queue.ts';
import { DiskRunner, FakeTmux, makeConfig, useScratch, fakeWatcher, specText } from './helpers.ts';
const scratch = useScratch();
it('H3: pending queue_rm is named and replace confirms once into a single watch step', async () => {
  const config = makeConfig(scratch.sub('replace'), 'mcp: {allow: [queue, queue_rm]}\ncapacity: {snapshot: false, codex_refresh: false}\n');
  const runner = new DiskRunner({dryRun: false, respond: new FakeTmux().respond});
  const ctx = new Context(runner, config, () => {}), deps = {context: () => ctx, notify: async () => {}};
  fakeWatcher(config);
  const spec = specText({task: 'SAME', agent: 'claude'}, scratch.sub('repo'), 'Replacement prompt.');
  await saveEntry(ctx, {seq: 1, order: 1, task: 'SAME', priority: 'normal', status: 'queued', queuedAt: new Date(runner.now()).toISOString(), agent: 'claude', model: 'sonnet', effort: 'high', after: [], spec: spec.replace('Replacement prompt.', 'Old prompt.')});
  const pending = await recordMcpRequest(ctx, {tool: 'queue_rm', args: {task: 'SAME'}, scope: null, key: 'rm', label: 'SAME', task: 'SAME'});
  const tool = MCP_TOOLS.find(t => t.name === 'queue')!;
  const call = (args: Record<string, unknown>) => tool.run(deps, z.object(tool.input).parse(args));
  const refused = await call({spec});
  assert.match(refused.text, /oczekuje queue_rm \(request /);
  assert.match(refused.text, new RegExp(pending.request.id));
  const preview = await call({spec, replace: true});
  assert.ok(!preview.isError, preview.text);
  const token = /preview_token: (\S+)/.exec(preview.text)![1];
  const confirmed = await call({confirm: true, preview_token: token});
  assert.ok(!confirmed.isError, confirmed.text); assert.match(confirmed.text, /^Accepted: queue/);
  assert.match(readQueue(config)[0]!.spec, /Old prompt/);
  const completed = await applyMcpRequests(ctx, {notify: async () => {}}, r => applyMcpRequest(deps, r));
  assert.deepEqual(completed.map(r => [r.tool, r.status, r.error]), [['queue_rm', 'done', undefined], ['queue', 'done', undefined]]);
  assert.equal(readQueue(config).length, 1); assert.match(readQueue(config)[0]!.spec, /Replacement prompt/);
  const replay = await call({confirm: true, preview_token: token}); assert.ok(!replay.isError, replay.text);
  assert.equal(readQueue(config).length, 1);
});
