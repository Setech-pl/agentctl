import assert from 'node:assert/strict';
import fs from 'node:fs';
import { describe, it } from 'node:test';
import { collectDisk, diskLevel, diskTick, DISK_INTERVAL_MS } from '../src/core/disk.ts';
import { readJournal } from '../src/core/journal.ts';
import { makeConfig, makeContext, useScratch, seedTask, DiskRunner } from './helpers.ts';
import { Context } from '../src/core/context.ts';
const scratch = useScratch();
const stat = (free: number) => (async () => ({ bsize: 1024, bavail: free / 1024, blocks: 1000 * 1024 ** 2 })) as unknown as typeof fs.promises.statfs;
describe('disk facts', () => {
  it('deduplicates devices, includes known project roots, and caches worktree size', async () => {
    const config = makeConfig(scratch.sub('disk'));
    const repo = scratch.sub('disk/repo');
    const wt = scratch.sub('disk/wt');
    const projectRoot = scratch.sub('disk/project-worktrees');
    fs.writeFileSync(`${repo}/.agentctl.yaml`, `worktree_root: ${projectRoot}\n`);
    fs.writeFileSync(`${wt}/data`, 'abc');
    seedTask(config, 'A-1', { repos: [{ path: repo, worktree: wt }] });
    const { ctx, runner } = makeContext(config);
    let calls = 0;
    const fake = (async (...args: Parameters<typeof fs.promises.statfs>) => { calls++; return stat(25 * 1024 ** 3)(...args); }) as typeof fs.promises.statfs;
    const first = await collectDisk(ctx, fake);
    assert.equal(first.volumes.length, 1);
    assert.equal(calls, 1);
    assert.ok(first.volumes[0]!.paths.includes(projectRoot));
    assert.equal(first.volumes[0]!.level, 'warn');
    assert.equal(first.worktreeBytes, 3);
    fs.writeFileSync(`${wt}/data`, 'abcdef');
    assert.equal((await collectDisk(ctx, fake)).worktreeBytes, 3);
    await runner.sleep(DISK_INTERVAL_MS);
    assert.equal((await collectDisk(ctx, fake)).worktreeBytes, 6);
  });
  it('reports n/d on permission failures and falls back to df when available', async () => {
    const config = makeConfig(scratch.sub('denied'));
    const fail = (async () => { throw new Error('EACCES'); }) as typeof fs.promises.statfs;
    const unknown = makeContext(config, { respond: () => ({ code: 1, stderr: 'denied' }) });
    const disk = await collectDisk(unknown.ctx, fail);
    assert.equal(disk.level, 'unknown');
    assert.equal(disk.volumes[0]!.availableBytes, null);
    assert.match(disk.volumes[0]!.error!, /EACCES/);
    const fallback = makeContext(config, { respond: (cmd) => cmd === 'df' ? { stdout: 'Filesystem 1024-blocks Used Available Capacity Mounted on\n/dev/disk 100000000 50000000 50000000 50% /\n' } : undefined });
    assert.equal((await collectDisk(fallback.ctx, fail)).volumes[0]!.availableBytes, 50000000 * 1024);
  });
  it('uses GiB thresholds and never guesses missing readings', () => {
    assert.equal(diskLevel(null, 50, 20), 'unknown');
    assert.equal(diskLevel(19 * 1024 ** 3, 50, 20), 'critical');
    assert.equal(diskLevel(20 * 1024 ** 3, 50, 20), 'warn');
    assert.equal(diskLevel(50 * 1024 ** 3, 50, 20), 'ok');
  });
  it('notifies and journals once per threshold transition across watcher restarts', async () => {
    const config = makeConfig(scratch.sub('transition'), 'disk: {warn_gb: 99999999, critical_gb: 99999998}\n');
    const runner = new DiskRunner({ dryRun: false });
    const ctx = new Context(runner, config, () => {});
    const notices: string[] = [];
    const notifier = { notify: async (_title: string, message: string) => { notices.push(message); } };
    await diskTick(ctx, notifier);
    await runner.sleep(DISK_INTERVAL_MS);
    await diskTick(ctx, notifier);
    assert.equal(notices.length, 1);
    config.disk.criticalGb = 0.000001;
    await runner.sleep(DISK_INTERVAL_MS);
    await diskTick(ctx, notifier);
    config.disk.warnGb = 0.000002;
    await runner.sleep(DISK_INTERVAL_MS);
    await diskTick(ctx, notifier);
    assert.deepEqual(readJournal(config).map((e) => e.kind), ['disk-critical', 'disk-warn', 'disk-ok']);
    assert.equal(notices.length, 3);
  });
});
