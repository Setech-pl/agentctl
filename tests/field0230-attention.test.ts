import assert from 'node:assert/strict';
import { it } from 'node:test';
import { Context } from '../src/core/context.ts';
import { attentionTick } from '../src/core/attention.ts';
import { collectStatus } from '../src/core/status.ts';
import { readWall } from '../src/core/wall.ts';
import { DiskRunner, FakeTmux, makeConfig, seedTask, useScratch } from './helpers.ts';
const scratch = useScratch();
it('F8: needs-trust/input escalate once after threshold across restarts, to owner WALL and configured phone', async () => {
  const config = makeConfig(scratch.sub('attention'), 'notify: {attention_after_min: 15, ntfy: {topic: test-only, server: "https://notify.invalid"}}');
  const tmux = new FakeTmux(); tmux.add('trust', 'Yes, I trust this folder'); tmux.add('input', 'Enter to select · Esc to cancel');
  seedTask(config, 'TRUST'); seedTask(config, 'INPUT');
  const runner = new DiskRunner({dryRun: false, startTime: Date.parse('2026-11-17T12:00Z'), respond: tmux.respond});
  const ctx = new Context(runner, config, () => {});
  let phones = 0;
  ctx.fetch = async () => {phones++; return new Response('', {status: 200});};
  const notices: string[] = [], notifier = {notify: async (_title: string, text: string) => {notices.push(text);}};
  const rows = await collectStatus(ctx);
  assert.deepEqual(new Set(rows.map(r => r.state)), new Set(['needs-trust', 'needs-input']));
  await attentionTick(ctx, rows, notifier);
  await runner.sleep(15 * 60000 - 1); await attentionTick(ctx, rows, notifier);
  assert.equal(notices.length, 0);
  await runner.sleep(2); await attentionTick(ctx, rows, notifier);
  assert.equal(notices.length, 2); assert.equal(phones, 2);
  const wall = readWall(ctx, {id: 'owner', kind: 'owner'}, {channel: 'agentctl'});
  assert.equal(wall.messages.length, 2);
  assert.ok(wall.messages.every(m => m.kind === 'decision-request' && m.to === 'owner'));
  const restart = new Context(runner, config, () => {}); restart.fetch = ctx.fetch;
  await runner.sleep(86400000); await attentionTick(restart, rows, notifier);
  await attentionTick(restart, rows.map(r => ({...r, state: 'working' as const})), notifier);
  await attentionTick(restart, rows, notifier); await runner.sleep(3600000); await attentionTick(restart, rows, notifier);
  assert.equal(notices.length, 2); assert.equal(phones, 2);
});
