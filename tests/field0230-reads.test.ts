import assert from 'node:assert/strict';
import fs from 'node:fs';
import { it } from 'node:test';
import { z } from 'zod';
import { Context } from '../src/core/context.ts';
import { MCP_TOOLS, publishMcpSnapshot } from '../src/core/mcp-tools.ts';
import { DiskRunner, FakeTmux, makeConfig, seedTask, useScratch } from './helpers.ts';
const scratch = useScratch();
it('F9: every tool accepts as; irrelevant identity is ignored in preview/confirm; expiry includes local time', async () => {
  for (const tool of MCP_TOOLS) assert.ok(tool.input.as, tool.name);
  const config = makeConfig(scratch.sub('as'), 'mcp: {allow: [pin]}');
  seedTask(config, 'PIN');
  const runner = new DiskRunner({dryRun: false, respond: new FakeTmux().respond});
  const deps = {context: () => new Context(runner, config, () => {}), notify: async () => {}};
  const tool = MCP_TOOLS.find(t => t.name === 'pin')!;
  const preview = await tool.run(deps, z.object(tool.input).parse({tasks: ['PIN'], as: 'chat:nc'}));
  assert.equal(preview.isError, undefined, preview.text);
  assert.match(preview.text, /expires_at_local: \d{4}-\d\d-\d\d \d\d:\d\d/);
  const token = /preview_token: (\S+)/.exec(preview.text)![1];
  const result = await tool.run(deps, {confirm: true, preview_token: token, as: 'chat:hems'});
  assert.equal(result.isError, undefined, result.text);
});
it('F9: cohort status uses the fresh watch sample with no task probes and overlap appears only for collisions', async t => {
  const config = makeConfig(scratch.sub('cohort'));
  const tmux = new FakeTmux(); tmux.add('nc', 'Working (esc to interrupt)'); tmux.add('hems', 'Working (esc to interrupt)');
  seedTask(config, 'NC', {cohort: 'NC'}); seedTask(config, 'HEMS', {cohort: 'HEMS'});
  let probes = 0;
  const runner = new DiskRunner({dryRun: false, respond: (cmd, args, opts) => {probes++; return tmux.respond(cmd, args, opts);}});
  const ctx = new Context(runner, config, () => {}), deps = {context: () => ctx, notify: async () => {}};
  await publishMcpSnapshot(ctx);
  const before = probes;
  t.mock.method(fs, 'readdirSync', () => {throw new Error('no inventory on a snapshot read');});
  const tool = MCP_TOOLS.find(t => t.name === 'status')!;
  const text = await tool.run(deps, {cohort: 'nc', as: 'chat:nc'});
  assert.match(text.text, /Watch snapshot age/); assert.match(text.text, /NC claude/);
  assert.doesNotMatch(text.text, /HEMS claude|overlap/);
  const json = JSON.parse((await tool.run(deps, {cohort: 'nc', format: 'json'})).text);
  assert.deepEqual(json.tasks.map((r: {task: string}) => r.task), ['NC']);
  assert.equal(probes, before);
});
