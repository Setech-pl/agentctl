import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { it } from 'node:test';
import { Context } from '../src/core/context.ts';
import { saveEntry } from '../src/core/queue.ts';
import { recordMcpRequest } from '../src/core/mcp-requests.ts';
import { watchTick, WatchMemory } from '../src/core/watch.ts';
import { readJournal } from '../src/core/journal.ts';
import { collectStatus } from '../src/core/status.ts';
import { DiskRunner, FakeTmux, makeConfig, seedTask, useScratch } from './helpers.ts';
const scratch = useScratch();
it('H1: a never-started queue_rm is cancelled before watch observes windows or publishes a snapshot', async () => {
  const config = makeConfig(scratch.sub('cancel'), 'mcp: {allow: [queue_rm]}\nqueue: {enabled: false}\ncapacity: {snapshot: false, codex_refresh: false}\n');
  const runner = new DiskRunner({dryRun: false, respond: new FakeTmux().respond});
  const ctx = new Context(runner, config, () => {});
  seedTask(config, 'WAIT', {started: '', promptDelivery: 'launching'});
  await saveEntry(ctx, {seq: 1, order: 1, task: 'WAIT', priority: 'normal', status: 'queued', queuedAt: new Date(runner.now()).toISOString(), agent: 'claude', model: 'sonnet', effort: 'high', after: [], spec: '---\ntask: WAIT\nagent: claude\n---\nWait.'});
  await recordMcpRequest(ctx, {tool: 'queue_rm', args: {task: 'WAIT'}, scope: null, key: 'rm', label: 'WAIT', task: 'WAIT'});
  const memory = new WatchMemory(); memory.started = true;
  const events = await watchTick(ctx, memory, {notify: async () => {}});
  await memory.queue.idle();
  assert.ok(!events.some(e => e.task === 'WAIT'), JSON.stringify(events));
  const row = (await collectStatus(ctx, {cachedOnly: true})).find(r => r.task === 'WAIT')!;
  assert.equal(row.state, 'cancelled'); assert.equal(row.hidden, true);
  const snapshot = JSON.parse(fs.readFileSync(path.join(config.stateDir, 'mcp-state-snapshot.json'), 'utf8'));
  assert.equal(snapshot.rows.find((r: {task: string}) => r.task === 'WAIT').state, 'cancelled');
  assert.ok(!readJournal(config).some(e => e.task === 'WAIT' && ['dead', 'tmux-lost'].includes(e.kind)));
});
