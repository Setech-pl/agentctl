import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { it } from 'node:test';
import { Context } from '../src/core/context.ts';
import { collectStatus } from '../src/core/status.ts';
import { limitedTick } from '../src/core/limited.ts';
import { collectLimits } from '../src/core/limits.ts';
import { queueTick, QueueMemory, saveEntry } from '../src/core/queue.ts';
import { readJournal } from '../src/core/journal.ts';
import { rememberSession } from '../src/core/usage-tap.ts';
import { parseClaudeEvent } from '../src/core/providers/claude-events.ts';
import type { AgentName } from '../src/core/config.ts';
import { DiskRunner, FakeTmux, makeConfig, seedTask, useScratch } from './helpers.ts';
const scratch = useScratch();
const now = Date.parse('2026-10-31T12:00:00Z');
const cases = JSON.parse(fs.readFileSync(new URL('./fixtures/provider-quota-errors.json', import.meta.url), 'utf8')) as {provider: AgentName; screen: string; reset: string | null}[];
for (const [index, fx] of cases.entries()) it(`G1b: ${fx.provider} fixture ${index} marks limited and holds starts without usage data`, async () => {
  const config = makeConfig(scratch.sub(`quota-${index}`), 'providers: [claude, codex, glm, kimi]\ncapacity: {snapshot: false, codex_refresh: false}\n');
  const tmux = new FakeTmux(); tmux.add('limited', fx.screen);
  const runner = new DiskRunner({dryRun: false, startTime: now, respond: tmux.respond}), ctx = new Context(runner, config, () => {});
  seedTask(config, 'LIMITED', {agent: fx.provider, started: new Date(now - 1000).toISOString()});
  const rows = await collectStatus(ctx, {progress: false}); assert.equal(rows[0]!.state, 'limited');
  const notifier = {notify: async () => {}};
  await limitedTick(ctx, rows, notifier); await limitedTick(ctx, rows, notifier);
  const hold = collectLimits(config, [], now).providers.find(p => p.agent === fx.provider)!.providerHold!;
  assert.equal(hold.source, 'automatic'); assert.equal(Date.parse(hold.until), fx.reset ? Date.parse(fx.reset) : now + 3600000);
  assert.equal(readJournal(config).filter(e => /błąd quota\/rate-limit/.test(e.text)).length, 1);
  await saveEntry(ctx, {seq: 1, order: 1, task: 'NEXT', direct: true, status: 'queued', priority: 'normal', queuedAt: new Date(now).toISOString(), agent: fx.provider, model: 'default', effort: 'high', after: [], spec: '---\ntask: UNUSED\n---\nWait.'});
  const memory = new QueueMemory(); assert.deepEqual(await queueTick(ctx, memory, notifier), []); await memory.idle();
  config.queue.enabled = false; await runner.sleep(Date.parse(hold.until) - now + 1); await queueTick(ctx, memory, notifier);
  await limitedTick(ctx, rows, notifier);
  assert.equal(collectLimits(config, [], runner.now()).providers.find(p => p.agent === fx.provider)!.providerHold, undefined, 'stale evidence never re-arms an expired hold');
});
it('G1b: pinned current-attempt transcript errors count; user and successful assistant text do not', async () => {
  const root = scratch.sub('transcript'), config = makeConfig(root, 'providers: [claude, codex, glm]\n');
  const tmux = new FakeTmux(); tmux.add('transcript', '❯ ');
  const runner = new DiskRunner({dryRun: false, startTime: now, respond: tmux.respond}), ctx = new Context(runner, config, () => {});
  seedTask(config, 'TRANSCRIPT', {agent: 'glm', started: new Date(now - 1000).toISOString()});
  const file = path.join(root, 'session.jsonl');
  const error = {timestamp: new Date(now).toISOString(), type: 'assistant', isApiErrorMessage: true, message: {role: 'assistant', content: [{type: 'text', text: 'API Error: 429 quota exhausted'}]}};
  fs.writeFileSync(file, JSON.stringify(error) + '\n');
  await rememberSession(runner, config, 'transcript', 'glm', {id: 'quota-session', transcript: file});
  assert.equal((await collectStatus(ctx, {progress: false}))[0]!.state, 'limited');
  fs.appendFileSync(file, JSON.stringify({timestamp: new Date(now + 1).toISOString(), type: 'user', message: {role: 'user', content: 'Explain quota exhausted errors'}}) + '\n');
  assert.notEqual((await collectStatus(ctx, {progress: false}))[0]!.state, 'limited');
  fs.appendFileSync(file, JSON.stringify({...error, isApiErrorMessage: false}) + '\n');
  assert.notEqual((await collectStatus(ctx, {progress: false}))[0]!.state, 'limited');
  assert.equal(parseClaudeEvent('stop-failure', {error: 'api_error', error_details: 'API Error: 429 insufficient balance'}, 'glm').outcome, 'limited');
});

it('G1b: custom screen limit patterns retain their replacement semantics', async () => {
  const config = makeConfig(scratch.sub('custom-pattern'), 'agents: {claude: {limit_patterns: ["^CUSTOM quota"]}}\n');
  const tmux = new FakeTmux(); tmux.add('custom', 'API Error: 429 quota exhausted\n❯ ');
  const runner = new DiskRunner({dryRun: false, startTime: now, respond: tmux.respond}), ctx = new Context(runner, config, () => {});
  seedTask(config, 'CUSTOM', {started: new Date(now - 1000).toISOString()});
  assert.notEqual((await collectStatus(ctx, {progress: false}))[0]!.state, 'limited');
});
