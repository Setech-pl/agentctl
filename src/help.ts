import type { Command, Option } from 'commander';
import { main, defaultDeps } from './cli.ts';
import { COMMAND_EXAMPLES, commandPath } from './examples.ts';

/*
 * docs/commands.md is generated from the command definitions in src/cli.ts (`npm run docs`); a test fails when the file is out of date.
 */

/** The command tree exactly as `agentctl` builds it, without running anything. */
export async function loadProgram(): Promise<Command> {
  let program: Command | undefined;
  await main(['--version'], { ...defaultDeps(), stdout: () => {}, stderr: () => {}, inspect: (p) => void (program = p) });
  if (!program) throw new Error('the command tree was not built');
  return program;
}

/** Every command below the root, parents before their subcommands, in the order they were defined. */
export function allCommands(program: Command): Command[] {
  return program.commands.flatMap((c) => [c, ...allCommands(c)]);
}

/** Text from a description into Markdown: `<task>` must not be taken for an HTML tag. */
const prose = (text: string): string => text.replace(/</g, '\\<');
const cell = (text: string): string => prose(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function optionNotes(o: Option): string {
  const notes: string[] = [];
  if (o.argChoices) notes.push(`one of ${o.argChoices.map((c) => `\`${c}\``).join(', ')}`);
  if (o.defaultValue !== undefined) notes.push(`default \`${String(o.defaultValue)}\``);
  if (o.mandatory) notes.push('required');
  return notes.join('; ');
}

function renderCommand(cmd: Command): string[] {
  const path = commandPath(cmd);
  const lines = [`## agentctl ${path}`, '', prose(cmd.description()), ''];
  const subs = cmd.commands.map((c) => `\`${commandPath(c)}\``);
  if (subs.length > 0) {
    const fallback = (cmd as unknown as { _defaultCommandName?: string })._defaultCommandName;
    lines.push(`Subcommands: ${subs.join(', ')}.${fallback ? ` Without a subcommand: \`${fallback}\`.` : ''}`, '');
  }
  lines.push('```', `agentctl ${path} ${cmd.usage()}`.trimEnd(), '```', '');
  if (cmd.registeredArguments.length > 0) {
    lines.push('| Argument | Meaning |', '|---|---|');
    for (const a of cmd.registeredArguments) {
      const shown = `${a.name()}${a.variadic ? '...' : ''}`;
      lines.push(`| \`${a.required ? `<${shown}>` : `[${shown}]`}\` | ${cell(a.description)} |`);
    }
    lines.push('');
  }
  if (cmd.options.length > 0) {
    lines.push('| Option | Meaning | Notes |', '|---|---|---|');
    for (const o of cmd.options) lines.push(`| \`${o.flags}\` | ${cell(o.description)} | ${cell(optionNotes(o))} |`);
    lines.push('');
  }
  const examples = COMMAND_EXAMPLES[path];
  if (examples && examples.length > 0) lines.push('Examples:', '', '```sh', ...examples, '```', '');
  return lines;
}

/** The text of docs/commands.md. */
export function renderCommandsMarkdown(program: Command): string {
  const commands = allCommands(program);
  const lines = [
    '<!-- Generated by `npm run docs` from the command definitions in src/cli.ts. Do not edit by hand. -->',
    '',
    '# Commands',
    '',
    `${prose(program.description())} The same text is what \`agentctl --help\` and \`agentctl <command> --help\` print.`,
    '',
    'Options of every command: `-h, --help`. Options of `agentctl` itself: `-V, --version`.',
    'Task IDs are case-insensitive and a unique prefix is enough for `attach`, `peek`, `hide`, `unhide`; the other commands take the full ID.',
    '',
    '| Command | What it does |',
    '|---|---|',
    ...commands.map((c) => `| [\`${commandPath(c)}\`](#agentctl-${commandPath(c).replace(/ /g, '-')}) | ${cell(c.description())} |`),
    '',
    ...commands.flatMap(renderCommand),
  ];
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}
